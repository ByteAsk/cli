#!/usr/bin/env python3
"""ByteAsk GDB bridge — ENGINE-OWNED script materialized into ~/.byteask.

Do NOT edit this file in ~/.byteask: it is engine-owned. The source of truth is
`ext/cpp-tools/byteask_gdb_bridge.py` in the byteask-engine tree, where it is
embedded into the binary at build time. The engine re-materializes it on startup
and OVERWRITES the on-disk copy whenever it differs from the embedded bytes.

WHAT IT DOES
------------
Sourcing this file inside gdb only DEFINES the `byteask-bridge` command — nothing
is armed and no socket is opened. When you run `byteask-bridge`, it opens a
private Unix socket (0700, owner-only) that the `byteask` AI assistant connects
to so it can help debug THIS live gdb session. Every command the AI runs is
echoed to your terminal, so you always see what it does. Read-only commands run
automatically; state-changing ones are proposed for you to approve (that policy
lives on the AI side). Disarm with `byteask-bridge-off`.

    (gdb) source ~/.byteask/byteask_gdb_bridge.py   # usually via ~/.gdbinit
    (gdb) byteask-bridge                            # arm when you want AI help

Run standalone (`python3 byteask_gdb_bridge.py`) it just prints usage.
"""

from __future__ import annotations

import json
import os
import signal
import socket
import sys
import threading
import time

__version__ = "0.2.3"

# Are we running inside gdb (sourced) or standalone (python3 …)?
try:
    import gdb  # type: ignore

    _IN_GDB = True
except Exception:  # pragma: no cover - only taken standalone
    gdb = None
    _IN_GDB = False

# Cap on output handed back to the AI (mirrors the Rust OUTPUT_CAP).
OUTPUT_CAP = 8000
# Bound the recorded command history so a long session can't grow unbounded.
HISTORY_MAX = 300
# How long a client may take to send its one command line. A client that
# connects and stays silent used to hold the (then single-threaded) server for
# 120 s, blocking every other attach and command.
REQUEST_READ_TIMEOUT = 10.0
# How long a command waits for gdb's main thread to pick it up and finish. The
# AI side waits 35 s for a reply, so this must stay below that. (The env
# override only exists so the integration test need not wait 30 s.)
try:
    REPLY_TIMEOUT = min(30.0, float(os.environ.get("BYTEASK_BRIDGE_REPLY_TIMEOUT", "30")))
except ValueError:
    REPLY_TIMEOUT = 30.0


# ─────────────────────────────── helpers ────────────────────────────────────

def _agent_dir() -> str:
    home = os.environ.get("BYTEASK_HOME") or os.path.join(os.path.expanduser("~"), ".byteask")
    return os.path.join(home, "gdb-agent")


def _set_cloexec(sock) -> None:
    """Belt-and-suspenders FD_CLOEXEC so the socket never leaks into an inferior
    started with `run`. (Python 3.4+ already sets this by default; make it
    explicit for the security review.)"""
    try:
        import fcntl

        flags = fcntl.fcntl(sock.fileno(), fcntl.F_GETFD)
        fcntl.fcntl(sock.fileno(), fcntl.F_SETFD, flags | fcntl.FD_CLOEXEC)
    except Exception:
        pass


def _is_interactive() -> bool:
    """Only arm in an interactive terminal — never in batch/scripted gdb (which
    still sources ~/.gdbinit). We test gdb's stdin fd 0 (a tty when a human is
    typing; a file/pipe under `gdb -batch`/`gdb < script`). NOTE: `sys.stdout`
    is gdb's *wrapped* stream inside gdb, so `sys.stdout.isatty()` is unreliable
    here — check the raw fd. A test hook forces it on."""
    if os.environ.get("BYTEASK_BRIDGE_FORCE") == "1":
        return True
    try:
        return bool(os.isatty(0))
    except Exception:
        return False


# `_run_on_gdb` timeout results (identity-compared sentinels).
_NOT_RUN = object()
_STILL_RUNNING = object()


def _text(result) -> str:
    """A `_run_on_gdb` result as text: "" for None or a timeout sentinel."""
    return result if isinstance(result, str) else ""


def _cap(text: str) -> str:
    if len(text) <= OUTPUT_CAP:
        return text
    return text[:OUTPUT_CAP] + "\n... [output truncated]"


# Commands that read program state and therefore need the inferior stopped.
# When the program is running we answer these instantly instead of blocking.
_STATE_QUERY_VERBS = {
    "bt", "backtrace", "where", "frame", "f", "up", "down", "info", "i",
    "list", "l", "print", "p", "output", "x", "whatis", "ptype",
    "disassemble", "disas", "thread",
}


def _is_state_query(command: str) -> bool:
    parts = command.strip().split(None, 1)
    return bool(parts) and parts[0].lower() in _STATE_QUERY_VERBS


def _logging_enabled() -> bool:
    try:
        return bool(gdb.parameter("logging enabled"))
    except Exception:
        return False


def _set_logging(on: bool) -> None:
    word = "on" if on else "off"
    try:
        gdb.execute(f"set logging enabled {word}")
    except gdb.error:
        gdb.execute(f"set logging {word}")  # gdb < 12


def _capture_via_log(command: str) -> str:
    """(main thread) Run `command` with its output redirected to a private
    log file, and decode the bytes leniently. gdb returns `to_string` output
    as UTF-8 and raises UnicodeDecodeError on anything else — `list` of a
    Latin-1 source did."""
    import tempfile

    fd, path = tempfile.mkstemp(prefix="byteask-gdb-", suffix=".log")
    os.close(fd)
    saved = {}
    for name in ("logging file", "logging overwrite", "logging redirect"):
        try:
            saved[name] = gdb.parameter(name)
        except Exception:
            pass
    try:
        gdb.execute(f"set logging file {path}")
        gdb.execute("set logging overwrite on")
        gdb.execute("set logging redirect on")
        _set_logging(True)
        try:
            gdb.execute(command)
        finally:
            _set_logging(False)
        with open(path, "rb") as handle:
            return handle.read().decode("utf-8", "replace")
    finally:
        for name, value in saved.items():
            try:
                if isinstance(value, bool):
                    value = "on" if value else "off"
                gdb.execute(f"set {name} {value}")
            except Exception:
                pass
        try:
            os.unlink(path)
        except OSError:
            pass


def _capture(command: str) -> str:
    """(main thread) Run `command` and return its output as text."""
    words = command.strip().split(None, 1)
    verb = words[0].lower() if words else ""
    # `list` prints the user's source bytes, which need not be UTF-8. It goes
    # through the log file up front: retrying after a decode error would run
    # it twice (and `list` moves its position). The user's own logging, if
    # on, is left alone.
    if verb in ("list", "l") and not _logging_enabled():
        return _capture_via_log(command)
    try:
        return gdb.execute(command, to_string=True)
    except UnicodeDecodeError:
        # It already ran; never run it again.
        return (
            "(the command ran, but its output is not valid UTF-8, so gdb could not return "
            "it as text)"
        )


def _run_and_echo(command: str) -> str:
    """(main thread) Echo the AI's command to the user's terminal, run it,
    echo the output too, and return the captured output."""
    gdb.write(f"[byteask] (gdb) {command}\n")
    out = _capture(command)
    if out:
        gdb.write(out if out.endswith("\n") else out + "\n")
    return out if out else "(ok)"


def _snapshot() -> str:
    """(main thread) Compact state summary for the AI on attach. Each command is
    ALSO echoed to the user's terminal (full transparency: pair mode shows every
    command it runs, including the attach-time state read)."""
    gdb.write("[byteask] attaching — reading initial state:\n")
    parts = []
    for title, cmd in (
        ("inferior", "info inferiors"),
        ("frame", "frame"),
        ("breakpoints", "info breakpoints"),
        ("backtrace", "bt 10"),
        ("source", "list"),
    ):
        try:
            out = _run_and_echo(cmd)
            parts.append(f"[{title}]\n{out.strip()}")
        except Exception:
            pass
    return "\n\n".join(parts) if parts else "(no state — program not running?)"


# ─────────────────────────────── history ────────────────────────────────────

def _latest_history_index() -> int:
    """(main thread) The newest entry number in gdb's command history."""
    latest = 0
    try:
        raw = gdb.execute("show commands", to_string=True)
    except Exception:
        return latest
    for line in raw.splitlines():
        parts = line.strip().split(None, 1)
        if parts and parts[0].isdigit():
            latest = max(latest, int(parts[0]))
    return latest


class _History:
    """Bounded, text-only log of commands (user-typed + AI-issued). We never
    re-execute anything to capture output — past output is stale by definition."""

    def __init__(self) -> None:
        self._items: list[tuple[str, str, str]] = []
        self._lock = threading.Lock()

    def add(self, command: str, source: str) -> None:
        with self._lock:
            self._items.append((time.strftime("%H:%M:%S"), source, command))
            if len(self._items) > HISTORY_MAX:
                self._items = self._items[-HISTORY_MAX:]

    def format(self, max_chars: int = OUTPUT_CAP - 200) -> str:
        """The MOST RECENT entries that fit in `max_chars`, oldest first, with a
        count of the older ones left out. (The caller's cap used to cut
        the tail, so with a long history the newest commands — the ones that
        matter — were the ones that vanished.)"""
        with self._lock:
            items = list(self._items)
        if not items:
            return "(no commands recorded yet)"
        lines = [f"{t}  [{s:5}]  {c}" for (t, s, c) in items]
        kept: list[str] = []
        used = 0
        for line in reversed(lines):
            if kept and used + len(line) + 1 > max_chars:
                break
            kept.append(line)
            used += len(line) + 1
        kept.reverse()
        omitted = len(lines) - len(kept)
        if omitted:
            kept.insert(0, f"({omitted} older entries omitted)")
        return "\n".join(kept)


# ─────────────────────────────── the bridge ─────────────────────────────────

class _Bridge:
    def __init__(self) -> None:
        self.running = False
        self.session_id = None
        self.sock_path = None
        self.info_path = None
        self.server = None
        self.thread = None
        self.history = _History()
        # Run-state, updated by cont/stop events on the main thread; read as a
        # plain bool from the server thread (GIL makes the read atomic). Simple
        # all-stop model; non-stop multi-thread is approximate (documented).
        self._inferior_running = False
        # Inferior pid, captured on the main thread at cont-time so the server
        # thread can SIGINT it (the portable interrupt when gdb.interrupt() is
        # absent, e.g. gdb < 14).
        self._inferior_pid = None
        # before_prompt history-delta cursor.
        self._hist_max_index = 0
        self._in_prompt_hook = False

    # -- gdb event handlers (all run on gdb's main thread) --

    def _on_cont(self, _event) -> None:
        self._inferior_running = True
        try:
            self._inferior_pid = gdb.selected_inferior().pid or None
        except Exception:
            pass

    def _on_stop(self, _event) -> None:
        self._inferior_running = False

    def _on_exited(self, _event) -> None:
        # A program that runs to its end fires `cont` then `exited` — never
        # `stop` (measured on gdb 13.1). Without this the bridge said "running"
        # forever after the exit: every state read was refused and `interrupt`
        # signalled a pid that no longer existed (or had been reused).
        self._inferior_running = False
        self._inferior_pid = None

    def _on_before_prompt(self) -> None:
        # Capture newly typed user commands via gdb's readline history. Never
        # re-executes them; best-effort — misses only unusual cases.
        if self._in_prompt_hook:
            return
        self._in_prompt_hook = True
        try:
            raw = gdb.execute("show commands", to_string=True)
            for line in raw.splitlines():
                parts = line.strip().split(None, 1)
                if len(parts) != 2:
                    continue
                try:
                    idx = int(parts[0])
                except ValueError:
                    continue
                if idx <= self._hist_max_index:
                    continue
                self._hist_max_index = idx
                cmd = parts[1]
                if cmd.startswith("byteask-bridge"):
                    continue
                self.history.add(cmd, "user")
        except Exception:
            pass
        finally:
            self._in_prompt_hook = False

    # -- lifecycle --

    def arm(self) -> None:
        if self.running:
            gdb.write(f"ByteAsk bridge already armed — session {self.session_id}.\n")
            return
        if not _is_interactive():
            gdb.write("ByteAsk bridge: not arming (non-interactive/batch gdb).\n")
            return
        directory = _agent_dir()
        try:
            os.makedirs(directory, mode=0o700, exist_ok=True)
            os.chmod(directory, 0o700)  # exist_ok won't tighten an existing dir
        except Exception as exc:
            gdb.write(f"ByteAsk bridge: cannot prepare {directory}: {exc}\n")
            return

        self.session_id = os.urandom(3).hex()  # 6 hex chars, human-readable
        pid = os.getpid()
        self.sock_path = os.path.join(directory, f"gdb-{pid}-{self.session_id}.sock")
        self.info_path = os.path.join(directory, f"gdb-{pid}-{self.session_id}.json")
        try:
            os.unlink(self.sock_path)
        except FileNotFoundError:
            pass
        except Exception:
            pass

        try:
            srv = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            _set_cloexec(srv)
            srv.bind(self.sock_path)
            os.chmod(self.sock_path, 0o600)
            srv.listen(4)
            srv.settimeout(1.0)
        except Exception as exc:
            gdb.write(f"ByteAsk bridge: cannot open socket: {exc}\n")
            return

        self.server = srv
        self.running = True
        # Only commands typed from now on are this session's history — not
        # what was typed before arming, nor a ~/.gdb_history gdb loaded.
        self._hist_max_index = _latest_history_index()
        for event, handler in (
            (gdb.events.cont, self._on_cont),
            (gdb.events.stop, self._on_stop),
            (gdb.events.exited, self._on_exited),
            (gdb.events.before_prompt, self._on_before_prompt),
        ):
            try:
                event.connect(handler)
            except Exception:
                pass
        self._write_info()
        self.thread = threading.Thread(target=self._serve, daemon=True)
        self.thread.start()
        gdb.write(
            f"ByteAsk bridge armed — session {self.session_id} (pid {pid}). "
            f"The AI can attach now; every command it runs is shown here.\n"
        )

    def off(self) -> None:
        if not self.running:
            gdb.write("ByteAsk bridge is not armed.\n")
            return
        self.running = False
        for event, handler in (
            (gdb.events.cont, self._on_cont),
            (gdb.events.stop, self._on_stop),
            (gdb.events.exited, self._on_exited),
            (gdb.events.before_prompt, self._on_before_prompt),
        ):
            try:
                event.disconnect(handler)
            except Exception:
                pass
        try:
            self.server.close()
        except Exception:
            pass
        for path in (self.sock_path, self.info_path):
            try:
                if path:
                    os.unlink(path)
            except FileNotFoundError:
                pass
            except Exception:
                pass
        gdb.write("ByteAsk bridge disarmed.\n")

    def status(self) -> None:
        if self.running:
            gdb.write(
                f"ByteAsk bridge: armed, session {self.session_id}, socket {self.sock_path}\n"
            )
        else:
            gdb.write("ByteAsk bridge: not armed. Run `byteask-bridge` to arm.\n")

    def _write_info(self) -> None:
        info = {
            "pid": os.getpid(),
            "session_id": self.session_id,
            "socket": self.sock_path,
            "started": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        try:
            info["program"] = gdb.execute("info inferiors", to_string=True).strip()
        except Exception:
            pass
        try:
            with open(self.info_path, "w") as handle:
                json.dump(info, handle)
            os.chmod(self.info_path, 0o600)
        except Exception:
            pass

    # -- server --

    def _serve(self) -> None:
        while self.running:
            try:
                conn, _ = self.server.accept()
            except socket.timeout:
                continue
            except OSError:
                break
            # One thread per connection, so a slow or silent client cannot
            # hold up every other attach and command.
            threading.Thread(target=self._serve_one, args=(conn,), daemon=True).start()

    def _serve_one(self, conn) -> None:
        try:
            _set_cloexec(conn)
            self._handle(conn)
        except Exception:
            pass
        finally:
            try:
                conn.close()
            except Exception:
                pass

    def _handle(self, conn) -> None:
        conn.settimeout(REQUEST_READ_TIMEOUT)
        data = b""
        while b"\n" not in data:
            chunk = conn.recv(4096)
            if not chunk:
                break
            data += chunk
        command = data.decode("utf-8", "replace").strip()
        if not command:
            conn.sendall(b"(empty command)\n")
            return
        reply = self._dispatch(command)
        if not reply.endswith("\n"):
            reply += "\n"
        conn.sendall(reply.encode("utf-8", "replace"))

    def _dispatch(self, command: str) -> str:
        if command == "__sessionid__":
            info = _text(self._run_on_gdb(lambda: gdb.execute("info inferiors", to_string=True)))
            return json.dumps(
                {"session_id": self.session_id, "pid": os.getpid(), "program": info.strip()}
            )
        if command == "__runstate__":
            return "running" if self._inferior_running else "stopped"
        if command == "__history__":
            return self.history.format()
        if command == "__interrupt__":
            return self._interrupt()
        if command == "__snapshot__":
            if self._inferior_running:
                return "Program is running — no snapshot. Use interrupt or wait for a stop."
            return _text(self._run_on_gdb(_snapshot)) or "(no state — gdb did not answer in time)"

        # A regular gdb command from the AI.
        if self._inferior_running and _is_state_query(command):
            return (
                "Program is running — can't read state now. "
                "Wait for a breakpoint/stop, or use the interrupt action."
            )
        def run_logged() -> str:
            # Recorded when gdb actually runs it (on the main thread), so a
            # command that was cancelled below never appears as executed.
            self.history.add(command, "agent")
            return _run_and_echo(command)

        out = self._run_on_gdb(run_logged)
        if out is _NOT_RUN:
            return (
                "NOT EXECUTED: gdb was busy (the user's own command, a pager prompt, or the "
                "program running) and did not pick this command up in time. It was cancelled "
                "and will NOT run later. Re-send it when gdb is back at its prompt."
            )
        if out is _STILL_RUNNING:
            return (
                "STILL RUNNING: gdb started this command but it has not finished (it may be "
                "running the program). It WILL complete on its own — do NOT send it again; "
                "use interrupt, or wait and check the state."
            )
        if out is None:
            return (
                "NOT EXECUTED: the program is running, so gdb cannot take commands now. "
                "Use interrupt or wait for a stop."
            )
        return _cap(out)

    def _interrupt(self) -> str:
        # Only a RUNNING program can be interrupted. SIGINT to a stopped
        # one stayed queued and fired on the next continue; after an exit it
        # went to a dead (or reused) pid.
        if not self._inferior_running:
            return (
                "Nothing to interrupt: the program is not running (it is stopped at a "
                "prompt, or has exited)."
            )
        # gdb.interrupt() (gdb 14+) is thread-safe (with post_event), so prefer
        # it. On older gdb it doesn't exist — fall back to SIGINT'ing the
        # inferior pid we captured at cont-time (os.kill is a plain syscall,
        # safe from this thread); gdb, ptracing the child, stops it.
        if hasattr(gdb, "interrupt"):
            try:
                gdb.interrupt()
                return "Interrupt sent (gdb.interrupt) — the program should stop shortly."
            except Exception:
                pass
        pid = self._inferior_pid
        if pid:
            try:
                os.kill(pid, signal.SIGINT)
                return "Interrupt sent (SIGINT to inferior) — the program should stop shortly."
            except Exception as exc:
                return f"interrupt failed: {exc}"
        return "Cannot interrupt: no running inferior known; press Ctrl-C in the gdb terminal."

    def _run_on_gdb(self, fn, timeout: float | None = None):
        """Marshal `fn` onto gdb's main thread and return its result.

        Returns None when the inferior is running (gdb won't service posted
        events until it stops — post_event = thread-safety, not liveness).
        On timeout returns _NOT_RUN when gdb never picked the task up — it is
        then CANCELLED, so it can never run later — or _STILL_RUNNING when it
        started and has not finished.

        A timed-out task used to stay queued and run whenever gdb next got
        to it, while the AI had been told it did not respond; a re-sent
        approved `set var a = a + 1` ran twice (40 -> 42)."""
        if timeout is None:
            timeout = REPLY_TIMEOUT
        if self._inferior_running:
            return None
        box: dict = {}
        done = threading.Event()
        gate = threading.Lock()
        state = {"started": False, "cancelled": False}

        def task() -> None:
            with gate:
                if state["cancelled"]:
                    return
                state["started"] = True
            try:
                box["r"] = fn()
            except Exception as exc:  # includes gdb.error
                box["r"] = f"error: {exc}"
            finally:
                done.set()

        try:
            gdb.post_event(task)
        except Exception as exc:
            return f"error posting to gdb: {exc}"
        if done.wait(timeout):
            return box.get("r")
        with gate:
            if not state["started"]:
                state["cancelled"] = True
                return _NOT_RUN
        return _STILL_RUNNING


# ─────────────────────────── gdb command surface ────────────────────────────

if _IN_GDB:
    _bridge = _Bridge()

    class _ArmCommand(gdb.Command):
        """Arm the ByteAsk AI debugging bridge for THIS gdb session (opens a
        private owner-only socket; the AI can then attach and help)."""

        def __init__(self) -> None:
            super().__init__("byteask-bridge", gdb.COMMAND_USER)

        def invoke(self, arg, from_tty) -> None:  # noqa: ARG002
            _bridge.arm()

    class _OffCommand(gdb.Command):
        """Disarm the ByteAsk AI debugging bridge (closes the socket)."""

        def __init__(self) -> None:
            super().__init__("byteask-bridge-off", gdb.COMMAND_USER)

        def invoke(self, arg, from_tty) -> None:  # noqa: ARG002
            _bridge.off()

    class _StatusCommand(gdb.Command):
        """Show ByteAsk bridge status."""

        def __init__(self) -> None:
            super().__init__("byteask-bridge-status", gdb.COMMAND_USER)

        def invoke(self, arg, from_tty) -> None:  # noqa: ARG002
            _bridge.status()

    _ArmCommand()
    _OffCommand()
    _StatusCommand()
    # NOTE: nothing is armed at load time. The user runs `byteask-bridge`.


def main(argv=None) -> int:
    print(f"ByteAsk GDB bridge v{__version__}")
    print("This script is meant to be sourced inside gdb:")
    print("  (gdb) source ~/.byteask/byteask_gdb_bridge.py")
    print("then arm it when you want AI help:")
    print("  (gdb) byteask-bridge")
    return 0


if __name__ == "__main__" and not _IN_GDB:
    raise SystemExit(main())
