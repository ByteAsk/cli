//! Guardrail: no prompt the model reads may name another vendor's coding agent.
//!
//! Why this is a test and not a sweep. ByteAsk's identity was never in the prompt —
//! it was a runtime patch. Upstream's instructions open "You are Codex, a coding agent
//! based on GPT-5", and the ONLY place that was ever corrected is
//! `gateway.scrub_identity()`, applied per request. So identity was right on the
//! managed path and wrong on every path that does not pass through the gateway: a
//! ChatGPT-subscription session (direct to the ChatGPT backend), BYOK on the user's
//! own key (sidecar, direct) and `self/*` (user endpoint, direct).
//!
//! With upstream's templates a subscription session, asked which model it was trained on,
//! answers "I'm Codex, based on GPT-6"; asked how it differs from Codex it
//! describes ByteAsk as "an environment that adds a C/C++ engineering toolkit around
//! Codex". The tool descriptions are clean — the premise it is given is not.
//!
//! The rebranding script cannot be the guard here: it rewrites quoted spans on a single line in
//! `*.rs`, so it never touched these `.md` templates at all. A test is what survives
//! the next upstream merge.
use std::path::Path;

/// Assets whose text is fed to the model. Paths are relative to `codex-rs/`.
const PROMPT_ASSET_DIRS: &[&str] = &[
    "core/templates",
    "prompts/templates",
    "memories/write/templates",
    "skills/src/assets/samples",
    "ext/memories/templates",
    "ext/goal/templates",
];

/// Spellings that identify the agent as somebody else's product.
///
/// Deliberately narrow: `codex_apps` (an MCP server id in
/// `consequential_tool_message_templates.json`), `.codex-plugin`, upstream URLs and
/// repository paths are FUNCTIONAL identifiers, not prose about who the agent is.
/// Renaming those breaks behaviour; this guard is about the sentence the model reads
/// and repeats.
const IDENTITY_LEAKS: &[&str] = &[
    "You are Codex",
    "As Codex,",
    // Agent `interface:` blocks are user-visible: a display name and a default prompt.
    // `product-docs` shipped `display_name: "OpenAI Docs"` with OpenAI's logo as its
    // icon, inside our binary.
    "display_name: \"OpenAI",
    "OpenAI Docs",
    "I am Codex",
    "managed by Codex",
    "generated by Codex",
    "use Codex/",
    "OpenAI's command-line coding agent",
    ".codex/config.toml",
];

fn repo_root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("codex-rs")
}

fn walk(dir: &Path, out: &mut Vec<std::path::PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, out);
        } else if matches!(
            path.extension().and_then(|e| e.to_str()),
            Some("md" | "txt" | "xml" | "yaml")
        ) {
            out.push(path);
        }
    }
}

#[test]
fn no_prompt_asset_tells_the_model_it_is_another_product() {
    let root = repo_root();
    let mut files = Vec::new();
    for dir in PROMPT_ASSET_DIRS {
        walk(&root.join(dir), &mut files);
    }
    assert!(
        files.len() > 20,
        "expected to scan the prompt assets, found {} files — did a directory move?",
        files.len()
    );

    let mut findings = Vec::new();
    for file in &files {
        let Ok(text) = std::fs::read_to_string(file) else {
            continue;
        };
        for leak in IDENTITY_LEAKS {
            if let Some(i) = text.find(leak) {
                let rel = file.strip_prefix(root).unwrap_or(file);
                findings.push(format!(
                    "  {}: ...{}...",
                    rel.display(),
                    text[i.saturating_sub(40)..(i + leak.len() + 40).min(text.len())]
                        .replace('\n', " ")
                ));
            }
        }
    }
    assert!(
        findings.is_empty(),
        "prompt assets identify the agent as another product. The model repeats this \
         verbatim on every path that does not pass through the gateway \
         (subscription / BYOK / self/*):\n{}",
        findings.join("\n")
    );
}
