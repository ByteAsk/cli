#!/usr/bin/env python3
"""Write UPSTREAM.md: the fork statement plus the generated list of upstream files ByteAsk has modified.

Usage: gen_upstream_md.py <repo> <upstream-base-rev> <head-rev> <upstream-version> <out-path> [--check]
With --check, exit 1 when the file on disk differs from what would be generated (for CI).
"""
import subprocess
import sys

repo, base, head, version, out = sys.argv[1:6]
check = "--check" in sys.argv[6:]


def git(*args):
    return subprocess.run(["git", "-C", repo, *args], check=True, capture_output=True, text=True).stdout


base_sha = git("rev-parse", f"{base}^{{commit}}").strip()
rows = [line.split("\t") for line in git("diff", "--name-status", "--no-renames", base_sha, head).splitlines()]
modified = sorted(p for st, p in rows if st == "M")
deleted = sorted(p for st, p in rows if st == "D")
added = [p for st, p in rows if st == "A"]


def by_dir(paths):
    groups = {}
    for p in paths:
        parts = p.split("/")
        key = "/".join(parts[:2]) if len(parts) > 2 else (parts[0] if len(parts) > 1 else "(repository root)")
        groups.setdefault(key, []).append(p)
    return groups


lines = [
    "# Relationship to OpenAI Codex CLI",
    "",
    "ByteAsk CLI is a fork of [OpenAI Codex CLI](https://github.com/openai/codex), which is licensed under the",
    "Apache License, Version 2.0. ByteAsk is not affiliated with, sponsored by, or endorsed by OpenAI.",
    "",
    "## Upstream base",
    "",
    f"- Upstream release: `{version}`",
    f"- Upstream commit: `{base_sha}`",
    "",
    "The git history up to that commit is upstream's own, unchanged, with its original authors.",
    "",
    "## How ByteAsk's changes are recorded",
    "",
    "ByteAsk's work up to v0.2.4 was developed in a private repository. It is published here as one commit on",
    "top of the upstream history. From then on, changes are made in this repository in the normal way.",
    "",
    "## Merging upstream",
    "",
    "We merge upstream stable releases (`rust-v*` tags), not `main`. For `README.md`, `LICENSE`, `NOTICE` and",
    "`.github/` at the repository root, this repository's version wins on every merge. New code goes under",
    "`codex-rs/ext/` where possible, so the set of modified upstream files stays small.",
    "",
    "## Files changed from upstream",
    "",
    "As required by section 4(b) of the Apache License, this is the list of upstream files that ByteAsk has",
    f"modified or removed, compared with upstream commit `{base_sha[:10]}`. It is generated by",
    "`scripts/gen_upstream_md.py` and checked in CI. ByteAsk has also added "
    f"{len(added)} files that do not exist upstream.",
    "",
    f"### Modified ({len(modified)})",
    "",
]
for key, paths in sorted(by_dir(modified).items()):
    lines.append(f"<details><summary><code>{key}</code> ({len(paths)})</summary>")
    lines.append("")
    lines.extend(f"- `{p}`" for p in paths)
    lines.append("")
    lines.append("</details>")
lines += ["", f"### Removed ({len(deleted)})", ""]
lines.extend(f"- `{p}`" for p in deleted)
text = "\n".join(lines) + "\n"

if check:
    try:
        current = open(out).read()
    except FileNotFoundError:
        current = ""
    if current != text:
        print(f"{out} is out of date; run scripts/gen_upstream_md.py", file=sys.stderr)
        sys.exit(1)
    print(f"{out} is up to date")
else:
    with open(out, "w") as fh:
        fh.write(text)
    print(f"wrote {out}: {len(modified)} modified, {len(deleted)} removed, {len(added)} added")
